#!/usr/bin/env python3
"""Generate src/Core/SjisTable.cs: a cp932 (Shift-JIS) double-byte decoding table.

VaM's Mono cannot decode code page 932 and plugins may not use System.Text code pages,
so the player carries its own table. 60 lead bytes (0x81-0x9F, 0xE0-0xFC) x 188 trail
bytes (0x40-0x7E, 0x80-0xFC). Undefined cells are U+0000.

Usage: python3 tools/gen_sjis_table.py > Custom/Scripts/Usermade/VamMmd/src/Core/SjisTable.cs
"""
leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
trails = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))
cells = []
for l in leads:
    for t in trails:
        try:
            s = bytes([l, t]).decode('cp932')
            c = ord(s) if len(s) == 1 and ord(s) < 0x10000 else 0
        except UnicodeDecodeError:
            c = 0
        cells.append(c)
assert len(cells) == 60 * 188
print('// Generated by tools/gen_sjis_table.py. Do not edit by hand.')
print('namespace VamMmd.Core')
print('{')
print('    internal static class SjisTable')
print('    {')
print('        public const int Leads = 60;')
print('        public const int Trails = 188;')
print('        public const string Data =')
per = 47
rows = [cells[i:i + per] for i in range(0, len(cells), per)]
for i, r in enumerate(rows):
    lit = ''.join('\\u%04X' % c for c in r)
    print('            "%s"%s' % (lit, ';' if i == len(rows) - 1 else ' +'))
print('    }')
print('}')
